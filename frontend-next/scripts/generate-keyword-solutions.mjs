import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(here, "../../PRINTKEE_COMPLETE_KEYWORD_MASTER.csv");
const outputPath = path.resolve(here, "../data/keywordSolutionSeeds.js");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }
  if (field || row.length) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }

  const headers = rows.shift();
  return rows.filter((values) => values.some(Boolean)).map((values) =>
    Object.fromEntries(headers.map((header, index) => [header, values[index] || ""]))
  );
}

const slugify = (value) => String(value)
  .toLowerCase()
  .replace(/&/g, " and ")
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-+|-+$/g, "");

const frequencyChoice = (values) => {
  const counts = new Map();
  values.filter(Boolean).forEach((value) => counts.set(value, (counts.get(value) || 0) + 1));
  return [...counts.entries()].sort((left, right) => right[1] - left[1] || left[0].localeCompare(right[0]))[0]?.[0] || "/contact";
};

const unsafeModifier = /\b(?:manufacturer|wholesale|near me|price)\b/i;
const records = parseCsv(fs.readFileSync(sourcePath, "utf8"));
const grouped = new Map();
for (const record of records) {
  const primary = record["Primary Keyword"]?.trim();
  if (!primary) continue;
  if (!grouped.has(primary)) grouped.set(primary, []);
  grouped.get(primary).push(record);
}

const seeds = [...grouped.entries()].map(([primaryKeyword, rows]) => {
  const availability = rows.map((row) => row["Product Availability"]);
  const targetCandidates = rows
    .map((row) => row["Recommended URL"])
    .filter((url) => url && url !== "/locations" && url !== "/contact");
  const recommendedUrl = frequencyChoice(targetCandidates.length ? targetCandidates : rows.map((row) => row["Recommended URL"]));
  const secondaryKeywords = [...new Set(rows
    .filter((row) => ["P1", "P2"].includes(row.Priority))
    .map((row) => row["Normalized Keyword"]?.trim())
    .filter((keyword) => keyword && keyword !== primaryKeyword && !unsafeModifier.test(keyword)))]
    .slice(0, 12);
  const indexable = recommendedUrl !== "/contact"
    && availability.some((value) => value === "AVAILABLE" || value === "PARTIALLY AVAILABLE");

  return {
    slug: slugify(primaryKeyword),
    primaryKeyword,
    category: frequencyChoice(rows.map((row) => row.Category)),
    topicCluster: frequencyChoice(rows.map((row) => row["Topic Cluster"])),
    searchIntent: frequencyChoice(rows.map((row) => row["Search Intent"])),
    buyerPersona: frequencyChoice(rows.map((row) => row["Buyer Persona"])),
    productAvailability: frequencyChoice(availability),
    recommendedUrl,
    secondaryKeywords,
    keywordCount: rows.length,
    indexable,
  };
}).sort((left, right) => left.primaryKeyword.localeCompare(right.primaryKeyword));

fs.writeFileSync(outputPath, `// Generated by scripts/generate-keyword-solutions.mjs. Do not edit by hand.\nexport default ${JSON.stringify(seeds, null, 2)};\n`);
console.log(`Generated ${seeds.length} keyword solution clusters at ${outputPath}`);
